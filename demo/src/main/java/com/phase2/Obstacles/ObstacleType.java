package com.phase2.Obstacles;

/**
 * The {@code ObstacleType} enum defines the various types of obstacles that can appear in the game.
 * <p>
 * Each obstacle type represents a unique kind of blocking object that players and enemies must navigate around.
 * </p>
 */
public enum ObstacleType {

    /**
     * Represents a bush obstacle in the game.
     */
    BUSH;
}
