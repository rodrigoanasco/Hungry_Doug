package com.phase2.Rewards;

/**
 * The {@code RewardType} enum defines the various types of rewards that can be collected by the player in the game.
 * <p>
 * Each reward type represents a unique collectible object that provides points or benefits to the player.
 * </p>
 */
public enum RewardType {

    /**
     * Represents an apple reward that provides a small number of points.
     */
    APPLE,

    /**
     * Represents a bone reward that is a key collectible for the player.
     */
    BONE,

    /**
     * Represents a steak reward that appears temporarily and provides higher points.
     */
    STEAK,

    /**
     * Represents a mushroom reward that provides a moderate number of points.
     */
    MUSHROOM;
}