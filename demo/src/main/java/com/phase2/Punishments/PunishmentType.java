package com.phase2.Punishments;

/**
 * The {@code PunishmentType} enum defines the various types of punishments that can be applied to the player in the game.
 * <p>
 * Each punishment type represents a unique kind of harmful object or condition
 * that affects the player's performance or score.
 * </p>
 */
public enum PunishmentType {

    /**
     * Represents a whiskey punishment that applies a penalty to the player.
     */
    WHISKEY,

    /**
     * Represents an onion punishment that applies a penalty to the player.
     */
    ONION,

    /**
     * Represents a chocolate punishment that applies a penalty to the player.
     */
    CHOCOLATE;
}